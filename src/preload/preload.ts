import { contextBridge, ipcRenderer, webUtils } from 'electron';

async function call(channel: string, ...args: unknown[]) {
  const res = await ipcRenderer.invoke(channel, ...args);
  if (!res.ok) throw new Error(res.error);
  return res.value;
}

